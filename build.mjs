// Build the browser artifact: vendor/mermaid.min.js + src/client.js -> client.js
//
// The output is the module-loader form a `dsh.client` bundle must ship:
//
//   window.__ModuleLoader__.load({ id, factory(require) { ...; return plugin } })
//
// `id` must equal the package name — the loader keys the module table by it and
// `dsh-client-modules` serves the file at /plugins/<row id>/client.js.
//
// Run with: node build.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const mermaidPath = join(root, 'vendor', 'mermaid.min.js')
const sourcePath = join(root, 'src', 'client.js')
const outPath = join(root, 'client.js')

if (!existsSync(mermaidPath)) {
  console.error('vendor/mermaid.min.js not found. Put mermaid dist/mermaid.min.js there first.')
  process.exit(1)
}

const mermaid = readFileSync(mermaidPath, 'utf8')

// Drop the devtest-only export block so the shipped artifact carries only the
// plugin surface.
const rendererSource = readFileSync(sourcePath, 'utf8')
const marker = /[ \t]*\/\/ @test-only:start[\s\S]*?\/\/ @test-only:end\n?/
if (!marker.test(rendererSource)) {
  console.error('src/client.js is missing the @test-only:start/end block; refusing to guess.')
  process.exit(1)
}
const renderer = rendererSource.replace(marker, '')

if (!renderer.includes('exports.apply = apply')) {
  console.error('src/client.js no longer exports `apply`; the factory would return no plugin.')
  process.exit(1)
}

const bundle = [
  '// Generated by build.mjs — edit src/client.js, not this file.',
  'window.__ModuleLoader__.load({',
  `\tid: ${JSON.stringify(manifest.name)},`,
  '\tfactory(require) {',
  '\t\tvoid require;',
  '\t\tvar module = { exports: {} };',
  '\t\tvar exports = module.exports;',
  '\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
  mermaid,
  renderer,
  '\t\treturn module.exports;',
  '\t}',
  '});',
  ''
].join('\n')

// Fail the build rather than ship something the browser cannot parse. The
// artifact is evaluated as a script, so a plain Function compile is the same
// check the engine will make.
try {
  new Function(bundle)
} catch (error) {
  console.error('generated bundle does not parse:', error.message)
  process.exit(1)
}

writeFileSync(outPath, bundle)
console.log(
  `built client.js — id ${manifest.name}, ${(bundle.length / 1048576).toFixed(2)} MiB`
)
